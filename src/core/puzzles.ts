function randomNumbers(count: number): number[] {
  return Array.from({ length: count }, () => 1 + Math.floor(Math.random() * 9))
}

function pickRandom<T>(items: T[]): T {
  return items[Math.floor(Math.random() * items.length)]
}

// checkNextPuzzle.mjs measured the retry loop below across all 45
// selections: without uniqueOnly, worst case stays in the low double
// digits. "3 Zahlen, nur ÷" is the one uniqueOnly selection without an
// exception list (concept 15.11) and needs real headroom: run against this
// exact nextPuzzle(), 20,000 calls failed 303/20,000 (1.5%) at a cap of
// 200, 49/20,000 (0.25%) at 300 — an earlier, unmeasured guess of "150 is
// enough" was wrong, since 150 is *smaller* than 200 and would have been
// worse — and 1/20,000 (0.005%) at 500. That last number is the real
// residual risk at this cap: small, not zero, and now measured rather than
// assumed.
const MAX_ATTEMPTS = 500

// How many draws that *did* produce a valid puzzle may be spent looking
// for one the player hasn't just seen, before settling for a repeat. The
// window `recent` asks to avoid (history.ts's RECENT_LIMIT) is a wish, not
// a constraint: a selection whose whole in-band pool is smaller than the
// window — two numbers, × and ÷, band klein has 19 puzzles in its entire
// search space — would otherwise loop to MAX_ATTEMPTS and throw, which is
// a far worse outcome than showing a puzzle twice.
//
// The budget is per number count because that is what a draw costs:
// `reachable` runs every permutation × composition × operator tuple, so a
// four-number draw is some two orders of magnitude dearer than a
// two-number one. It is also exactly the other way round from where the
// budget is needed — the thin pools are all two-number selections, while
// no four-number selection has a pool anywhere near the window, so its
// budget is never spent in the first place.
function preferenceAttempts(numbers: PuzzleSettings['numbers']): number {
  return numbers === 4 ? 25 : 250
}

/**
 * How many of the selected operators a puzzle should ideally *need* — the
 * most any single solution could use, which is one per operator position:
 * 1 for two numbers (there is only one position, so the whole question is
 * moot), 2 for three numbers, and up to 3 for four.
 *
 * A preference, never a requirement. Measured exhaustively over the whole
 * search space: with `{+,−}` or `{×,÷}` selected, *no* puzzle at any number
 * count needs both operators — the bracket turns one into the other
 * (`a−(b−c) = a−b+c`, `a÷(b÷c) = a·c÷b`), so 550 of 550 three-number `+−`
 * puzzles and 297 of 297 `×÷` ones are single-operator by construction.
 * And where mixing is possible it is sometimes scarce: `3 Zahlen, +÷,
 * groß` has 20 mixing puzzles against 201 in total. Insisting would either
 * be impossible or would shrink some selections to a pool small enough to
 * bring the repeats back (`4 Zahlen, +−÷, mittel` goes from 3405 puzzles
 * to 30). So the draw asks for this and settles for less.
 */
function preferredDistinctOps(settings: PuzzleSettings): number {
  return Math.min(settings.ops.length, settings.numbers - 1)
}

/**
 * How many distinct operators a puzzle must *need* before the draw will
 * offer it — a floor, replacing the maximum this used to demand.
 *
 * The maximum was added so that picking four operators would not feel like
 * picking one (`5 + 5 + 5 + 5`). It worked, and it was also the single
 * biggest cause of the monotony the product owner reported: demanding three
 * distinct operators from four numbers admits 3 of the 25 shapes the pool
 * holds, which is why 91% of `4 Zahlen, alle vier, groß` came back as
 * `(n+n)×n−n`. A ceiling was the wrong tool; a floor kills `5+5+5+5`
 * outright and leaves 71–97% of each pool intact.
 *
 * Two selections cannot meet a floor of two and are carved out rather than
 * left to starve:
 *  - two numbers, where there is only one operator position at all;
 *  - `{+,−}`, where a−(b−c) = a−b+c stays on the whole numbers, so a
 *    one-operator route always survives. `{×,÷}` used to be carved out for
 *    the same reason and no longer is: its identity a÷(b÷c) = a·c÷b goes
 *    through a fraction, and fractional routes no longer count, so 14% of
 *    three-number and 48% of four-number ×÷ puzzles do need both.
 */
function operatorFloor(settings: PuzzleSettings): number {
  if (settings.numbers < 3 || settings.ops.length < 2) return 1
  if (settings.ops.every(op => op === '+' || op === '-')) return 1
  return 2
}

/** How many puzzles back the draw remembers *shapes*, when the caller keeps a window. */
export const SHAPE_WINDOW = 12

/**
 * A fresh puzzle for these settings, generated on the device (concept
 * 15.10): draw random numbers, ask the solver what's reachable, keep it if
 * the target lands in the selected band, otherwise draw again. The two
 * settings combinations with a thin uniqueOnly pool (concept 15.11) skip
 * the draw loop and pick straight from their exception list instead.
 *
 * `recent` is history.ts's window of recently played puzzles (signatures,
 * see `puzzleSignature`); the draw avoids them where it can. Nothing else
 * about the draw changes, and an empty window is exactly the old
 * behaviour.
 */
export function nextPuzzle(
  settings: PuzzleSettings,
  recent: readonly string[] = [],
  recentShapes: readonly string[] = [],
): Puzzle {
  const row = bandRow(settings)
  const [lo, hi] = row.bands[Math.min(settings.band, row.bands.length - 1)]
  const avoid = new Set(recent)

  if (settings.uniqueOnly) {
    const exceptions = exceptionList(settings)
    if (exceptions) {
      const inBand = exceptions.filter(([, target]) => target >= lo && target <= hi)
      const fresh = inBand.filter(([numbers, target]) => !avoid.has(puzzleSignature({ numbers, target })))
      const [numbers, target] = pickRandom(fresh.length > 0 ? fresh : inBand)
      const shape = reachable(numbers, settings.ops).find(e => e.target === target)
      return { numbers: [...numbers], target, pattern: shape?.pattern }
    }
  }

  // Where each remembered puzzle, and each remembered shape, sits in its
  // window: 0 is longest ago, the last index is the one just played, -1 is
  // one the player has not seen. Lower is better in both, so an unseen
  // puzzle and an unseen shape both score -1.
  const seenAt = new Map(recent.map((signature, i) => [signature, i]))
  const shapeAt = new Map(recentShapes.map((pattern, i) => [pattern, i]))
  const floor = operatorFloor(settings)
  const budget = preferenceAttempts(settings.numbers)
  const relaxEvery = Math.max(1, Math.ceil(budget / 2))
  let asking = floor
  let spent = 0

  interface Candidate { puzzle: Puzzle; seen: number; shape: number; unclean: number; metFloor: boolean }
  // Preference order, lower better: a puzzle the player has not just seen,
  // then a shape they have not just seen, then one that needs the operators
  // asked for, then one that wastes no chip.
  const rank = (c: Candidate): number[] => [c.seen, c.shape, c.metFloor ? 0 : 1, c.unclean]
  let best: Candidate | null = null

  for (let attempt = 0; attempt < MAX_ATTEMPTS; attempt++) {
    const numbers = randomNumbers(settings.numbers)
    const candidates = reachable(numbers, settings.ops).filter(
      e => e.target >= lo && e.target <= hi &&
        // The whole-number rule is a refusal, not a ranking: a target whose
        // only route runs through 1/81 is not a puzzle for this audience.
        e.wholeSolution &&
        (!settings.uniqueOnly || e.uniqueSolution),
    )
    if (candidates.length === 0) continue

    // Ask for the floor where this draw can meet it, and settle for what it
    // has where it cannot — a draw that offers nothing at the floor is not
    // a reason to throw away the draw.
    const atFloor = candidates.filter(e => e.minDistinctOps >= asking)
    const pool = atFloor.length > 0 ? atFloor : candidates
    const metFloor = atFloor.length > 0

    const scored: Candidate[] = pool.map(e => ({
      puzzle: { numbers, target: e.target, pattern: e.pattern },
      seen: seenAt.get(puzzleSignature({ numbers, target: e.target })) ?? -1,
      shape: shapeAt.get(e.pattern) ?? -1,
      unclean: e.cleanSolution ? 0 : 1,
      metFloor,
    }))
    // The whole point of the change: among candidates that tie on every
    // preference, pick at *random*. Taking the first one — which is what a
    // strict > comparison against a running best does — hands the choice to
    // reachable()'s enumeration order, and that order is fixed: flat
    // arrangements before bracketed ones, operator tuples in + − × ÷ order.
    // Brackets lost every tie by construction.
    let bestKey = rank(scored[0])
    for (const c of scored) {
      const key = rank(c)
      if (lexLess(key, bestKey)) bestKey = key
    }
    const tied = scored.filter(c => lexEqual(rank(c), bestKey))
    const chosen = pickRandom(tied)

    // Nothing better exists than an unseen puzzle in an unseen shape that
    // needs the operators asked for and wastes no chip.
    if (chosen.seen === -1 && chosen.shape === -1 && chosen.metFloor && chosen.unclean === 0) return chosen.puzzle
    if (!best || lexLess(rank(chosen), rank(best))) best = chosen

    spent += 1
    if (spent >= budget) return best.puzzle
    // The floor is unsatisfiable in some bands — `3 Zahlen, +÷, groß` has
    // only 20 puzzles that clear it, against a 30-puzzle history window —
    // so it gives way rather than spending the whole budget hunting.
    if (asking > 1 && spent % relaxEvery === 0) asking = 1
  }

  if (best) return best.puzzle

  throw new Error(
    `nextPuzzle: no candidate found after ${MAX_ATTEMPTS} attempts for ${settings.numbers} numbers, ` +
    `ops "${settings.ops.join('')}", band ${settings.band}${settings.uniqueOnly ? ', uniqueOnly' : ''} — ` +
    'settings.ts should not be offering this combination (concept 15.6/15.9).',
  )
}

/** Lexicographic comparison of two equal-length preference keys, lower being better. */
function lexLess(a: number[], b: number[]): boolean {
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== b[i]) return a[i] < b[i]
  }
  return false
}

function lexEqual(a: number[], b: number[]): boolean {
  return a.every((v, i) => v === b[i])
}

/**
 * Whether concept 15.6's uniqueOnly switch has anything to offer.
 *
 * Band-aware, because a selection can have unique-solution puzzles and a
 * *band* of it have none: `3 Zahlen, +÷` has 74 in all and not one in groß,
 * so leaving the switch on there made nextPuzzle exhaust its attempts and
 * throw — the same class of blank screen `reconcile` was written to prevent,
 * one level further in. Called without a band it answers for the selection
 * as a whole, which is what the panel needs before a band is chosen.
 */
export function uniqueOnlyAvailable(
  numbers: PuzzleSettings['numbers'],
  ops: Operator[],
  band?: number,
): boolean {
  const row = BAND_TABLE[`${numbers}-${opsMask(ops)}`]
  if (row === undefined) return false
  if (band === undefined) return row.unique > 0
  return (row.uniqueBands[Math.min(band, row.uniqueBands.length - 1)] ?? 0) > 0
}

/**
 * The three bands' [lo, hi] target ranges for a selection (concept 15.5) —
 * what the selection panel (concept 15.6) shows under each band chip, and
 * what the header's own summary chip (concept 12.7) shows for the current
 * one. `band`/`uniqueOnly` don't affect which row this reads, so they're
 * fixed placeholders here rather than parameters — every (numbers, ops)
 * pair the 45-row table has an entry for is a valid selection (concept
 * 15.5: "kein einziges Band leer").
 */
export function bandRanges(numbers: PuzzleSettings['numbers'], ops: Operator[]): [number, number][] {
  return bandRow({ numbers, ops, band: 0, uniqueOnly: false }).bands.map(([lo, hi]) => [lo, hi])
}

/**
 * How many bands this selection offers — one, two or three (see BandRow).
 * `useSettings` clamps a stored band against this, since a player can carry
 * band 2 into a selection that has only one.
 */
export function bandCount(numbers: PuzzleSettings['numbers'], ops: Operator[]): number {
  return bandRow({ numbers, ops, band: 0, uniqueOnly: false }).bands.length
}
