// Generates a puzzle on the device instead of loading one from a bank
// (concept 15.10 — the bank was dropped: generating one puzzle is fast
// enough to do it live, and a PWA has no reason to preload a puzzle it
// won't play). No React import, no network access — see CLAUDE.md's rule
// that `core/` is pure TypeScript.
//
// The depth-1 evaluator this is built on lives in solver.ts, shared with
// the (not yet implemented) hint system per concept 15.3's "ein Modell für
// Generator und Löser".

import { reachable } from './solver'
import type { Operator } from './expression'

export type { Operator }

/** The subset of Settings (concept section 11) that picking a puzzle needs. */
export interface PuzzleSettings {
  numbers: 2 | 3 | 4
  ops: Operator[] // at least one
  band: 0 | 1 | 2 // klein · mittel · groß (concept 15.5)
  uniqueOnly: boolean
}

export interface Puzzle {
  numbers: number[]
  target: number
  /**
   * The shape of the solution a player is likeliest to find (`(n+n)×n−n`).
   * Set by `nextPuzzle`, so the caller can feed it back as the shape window
   * on the next draw; nothing about a puzzle's identity depends on it.
   */
  pattern?: string
}

/**
 * Sorted numbers and the target — what makes two puzzles "the same" to a
 * player: the same chips and the same goal, whatever order they happened
 * to be drawn in. `history.ts` keeps a window of these; `nextPuzzle`
 * takes that window and draws around it.
 */
export function puzzleSignature(puzzle: Puzzle): string {
  return `${[...puzzle.numbers].sort((a, b) => a - b).join(',')}=${puzzle.target}`
}

const ALL_OPS: Operator[] = ['+', '-', '*', '/']

function opsMask(ops: Operator[]): number {
  return ALL_OPS.reduce((m, op, i) => (ops.includes(op) ? m | (1 << i) : m), 0)
}

interface BandRow {
  total: number
  unique: number
  /** How many of those sit in each band — see uniqueOnlyAvailable. */
  uniqueBands: number[]
  /**
   * One to three [lo, hi] target ranges. Not always three: a band is a
   * slice of target magnitude and magnitude is a proxy for operator, so
   * with two single digits — where a − b ≤ 8 and a ÷ b ≤ 9 while a × b
   * reaches 81 — a third band starting above 12 cannot contain − or ÷ at
   * all, and no boundary placement fixes it. Those selections get one band
   * covering their whole range instead of three, two of which would be a
   * lie. 28 of the 33 selections a player can actually reach still have
   * three (concept 15.6 requires at least two operators, so the 12
   * single-operator rows here are unreachable — kept because the table is
   * keyed by subset and nothing gains from the gaps).
   */
  bands: [number, number][]
}

